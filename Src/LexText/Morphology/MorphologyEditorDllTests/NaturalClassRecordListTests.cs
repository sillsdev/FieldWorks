using System.Collections.Generic;
using System.Linq;
using NUnit.Framework;
using SIL.LCModel;

namespace SIL.FieldWorks.XWorks.MorphologyEditor
{
	/// <summary>
	/// Tests to confirm that <see cref="NaturalClassRecordList"/> includes every
	/// natural class except a feature-based one generated automatically for a rule.
	/// </summary>
	[TestFixture]
	public class NaturalClassRecordListTests : RuleFormulaVcTestBase
	{
		private IEnumerable<int> NCRecordList(params ICmObject[] natClasses)
		{
			return NaturalClassRecordList.ExcludeAutoGenerated(
				natClasses.Select(nc => nc.Hvo), Cache);
		}
		[Test]
		public void AutoGeneratedClass_IsExcluded()
		{
			IPhNCFeatures natClass = AddAutoGeneratedFeatureNaturalClass("s to n",
				new Dictionary<string, string> { { "vd", "+" } });

			// Since the only NC is autogenerated, the NC record list should be empty
			Assert.That(NCRecordList(natClass), Is.Empty);
		}

		[Test]
		public void NamedFeatureClass_IsIncluded()
		{
			IPhNCFeatures natClass = AddFeatureNaturalClass("Voiced", "Vd",
				new Dictionary<string, string> { { "vd", "+" } });

			Assert.That(NCRecordList(natClass), Is.EqualTo(new[] { natClass.Hvo }));
		}

		/// <summary>
		/// A feature-based class the user creates starts with no name, so an unnamed class must
		/// be included for the user to be able to name it.
		/// </summary>
		[Test]
		public void UnnamedFeatureClass_IsIncluded()
		{
			IPhNCFeatures natClass = AddFeatureNaturalClass(null, null,
				new Dictionary<string, string> { { "vd", "+" } });

			Assert.That(NCRecordList(natClass), Is.EqualTo(new[] { natClass.Hvo }));
		}

		[Test]
		public void SegmentClass_IsIncluded()
		{
			IPhNCSegments natClass = AddSegmentNaturalClass("Vowels", "V");

			Assert.That(NCRecordList(natClass), Is.EqualTo(new[] { natClass.Hvo }));
		}

		/// <summary>
		/// A class given an abbreviation by the user is considered user defined,
		/// so it should display in the NC list.
		/// </summary>
		[Test]
		public void AbbreviatedGeneratedClass_IsIncluded()
		{
			IPhNCFeatures natClass = AddAutoGeneratedFeatureNaturalClass("s to n",
				new Dictionary<string, string> { { "vd", "+" } });
			natClass.Abbreviation.SetAnalysisDefaultWritingSystem("Vd");

			Assert.That(NCRecordList(natClass), Is.EqualTo(new[] { natClass.Hvo }));
		}

		/// <summary>
		/// A class with the "shared" prefix is not considered user defined if it is used
		/// by at most one rule, so it should not display in the NC list.
		/// </summary>
		[Test]
		public void PrefixedClassUsedByOneRule_IsExcluded()
		{
			IPhNCFeatures natClass = AddAutoGeneratedFeatureNaturalClass("s to n",
				new Dictionary<string, string> { { "vd", "+" } });
			natClass.Name.SetUserWritingSystem(string.Format(MEStrings.ksRuleNCSharedNameFormat,
				natClass.Name.UserDefaultWritingSystem.Text));
			AddStrucDescNCContext(AddRegularRule("rule A"), natClass);

			Assert.That(NCRecordList(natClass), Is.Empty);
		}

		/// <summary>
		/// A class used by more than one rule is considered user defined,
		/// so it should display in the NC list.
		/// </summary>
		[Test]
		public void ClassSharedByTwoRules_IsIncluded()
		{
			IPhNCFeatures natClass = AddAutoGeneratedFeatureNaturalClass("s to n",
				new Dictionary<string, string> { { "vd", "+" } });
			AddStrucDescNCContext(AddRegularRule("rule A"), natClass);
			AddStrucDescNCContext(AddRegularRule("rule B"), natClass);

			Assert.That(NCRecordList(natClass), Is.EqualTo(new[] { natClass.Hvo }));
		}
	}
}
