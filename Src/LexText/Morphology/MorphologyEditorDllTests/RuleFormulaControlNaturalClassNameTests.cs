using NUnit.Framework;
using SIL.LCModel;
using SIL.LCModel.Core.Text;
using SIL.LCModel.Core.WritingSystems;
using FeatVals = System.Collections.Generic.Dictionary<string, string>;

namespace SIL.FieldWorks.XWorks.MorphologyEditor
{
	/// <summary>
	/// Tests which feature-based natural classes count as user defined.
	/// A user defined NC must either:
	/// 1. have a name or abbreviation the user gave it.
	/// 2. be shared by two or more rules.
	///
	/// A rule formula draws a user defined class as an abbreviation and draws an
	/// auto-generated class as a feature list.
	///
	/// Combinations of user given, generated, or absent name/abbrevation and shared
	/// status are tested here to confirm that NCs are correctly classified as
	/// user defined or auto-generated.
	/// </summary>
	[TestFixture]
	public class RuleFormulaControlNaturalClassNameTests : RuleFormulaVcTestBase
	{
		[Test]
		public void NoClass_IsNotUserDefined()
		{
			Assert.That(RuleFormulaControl.IsFeatureBasedNCUserDefined(null), Is.False);
		}

		/// <summary>
		/// A user defined class can have no name, while an auto-generated one will always have
		/// a generated name. Check that if the class has no name, it is flagged as user defined.
		/// </summary>
		[Test]
		public void ClassWithNoName_IsUserDefined()
		{
			IPhNCFeatures natClass = AddFeatureNaturalClass(null, "Vd",
				new FeatVals { { "vd", "+" } });

			Assert.That(RuleFormulaControl.IsFeatureBasedNCUserDefined(natClass), Is.True,
				"an unnamed class must be user defined");
		}

		/// <summary>
		/// A user defined class can have an empty name, while an auto-generated one will always
		/// have a nonempty generated name. Check that if the class's name is empty,
		/// it is flagged as user defined.
		/// </summary>
		[Test]
		public void ClassWithAnEmptyName_IsUserDefined()
		{
			IPhNCFeatures natClass = AddFeatureNaturalClass(string.Empty, "Vd",
				new FeatVals { { "vd", "+" } });

			Assert.That(RuleFormulaControl.IsFeatureBasedNCUserDefined(natClass), Is.True,
				"a class with an empty name must be user defined");
		}

		[Test]
		public void ClassNamedForARule_IsNotUserDefined()
		{
			IPhNCFeatures natClass = AddAutoGeneratedFeatureNaturalClass("s to n",
				new FeatVals { { "vd", "+" } });

			Assert.That(RuleFormulaControl.IsFeatureBasedNCUserDefined(natClass), Is.False);
		}

		/// <summary>
		/// If a project contains a NC whose name was generated but a user has added text before
		/// or after the generated name, it is user defined.
		/// </summary>
		[Test]
		public void ClassNamedForARuleWithUserAssignedPrefixOrPostfix_IsUserDefined()
		{
			IPhNCFeatures natClass = AddFeatureNaturalClass(null, null,
				new FeatVals { { "vd", "+" } });
			natClass.Name.SetUserWritingSystem("Phonemes s and t - "
				+ string.Format(MEStrings.ksRuleNCFeatsName, "s to n"));
			Assert.That(RuleFormulaControl.IsFeatureBasedNCUserDefined(natClass), Is.True);
			natClass.Name.SetUserWritingSystem(string.Format(MEStrings.ksRuleNCFeatsName, "s to n")
				+ " - phonemes s and t");
			Assert.That(RuleFormulaControl.IsFeatureBasedNCUserDefined(natClass), Is.True);
		}

		[Test]
		public void NamedClass_IsUserDefined()
		{
			IPhNCFeatures natClass = AddFeatureNaturalClass("Voiced", "Vd",
				new FeatVals { { "vd", "+" } });

			Assert.That(RuleFormulaControl.IsFeatureBasedNCUserDefined(natClass), Is.True);
		}

		/// <summary>
		/// The natural class editor writes a name into the analysis writing systems while the
		/// check reads the user writing system. A project whose analysis language differs from
		/// its interface language must still have its named classes qualify.
		/// </summary>
		[Test]
		public void ClassNamedInAnAnalysisWritingSystemOtherThanTheUserOne_IsUserDefined()
		{
			Cache.ServiceLocator.WritingSystemManager.GetOrSet("de",
				out CoreWritingSystemDefinition german);
			Cache.LanguageProject.AddToCurrentAnalysisWritingSystems(german);
			IPhNCFeatures natClass = AddFeatureNaturalClass(null, "Vd",
				new FeatVals { { "vd", "+" } });
			natClass.Name.set_String(german.Handle,
				TsStringUtils.MakeString("Stimmhaft", german.Handle));
			Assert.That(natClass.Name.UserDefaultWritingSystem.Text, Is.EqualTo("Stimmhaft"),
				"the name must reach the check through the analysis writing system, "
				+ "not through a placeholder");

			Assert.That(RuleFormulaControl.IsFeatureBasedNCUserDefined(natClass), Is.True);
		}

		[Test]
		public void NamedClassWithNoFeatures_IsUserDefined()
		{
			IPhNCFeatures natClass = AddFeatureNaturalClass("Voiced", "Vd", new FeatVals());

			Assert.That(RuleFormulaControl.IsFeatureBasedNCUserDefined(natClass), Is.True,
				"a name qualifies a class whatever it carries for features");
		}

		/// <summary>
		/// No class is neither user defined nor auto-generated.
		/// </summary>
		[Test]
		public void NullClass_IsNotAutoGenerated()
		{
			Assert.That(RuleFormulaControl.IsAutoGeneratedNaturalClass(null), Is.False);
		}

		/// <summary>
		/// A translation may put the rule name first, leaving no generated text before the
		/// placeholder. Its generated names are still recognized, but ordinary names are not.
		/// </summary>
		[Test]
		public void FormatStartingWithRuleName_RecognisesGeneratedName()
		{
			const string format = "{0} rule: created automatically";

			Assert.That(RuleFormulaControl.IsAutoGeneratedName(string.Format(format, "s to n"), format),
				Is.True, "a name generated from the format is recognized");
			Assert.That(RuleFormulaControl.IsAutoGeneratedName("Voiced", format), Is.False,
				"an empty stub before the rule name must not match every name");
		}

		/// <summary>
		/// A translation lacking the rule name placeholder must not break recognition; no name
		/// counts as generated from it.
		/// </summary>
		[Test]
		public void FormatWithoutPlaceholder_RecognisesNothing()
		{
			const string format = "Created automatically for rule";

			Assert.That(RuleFormulaControl.IsAutoGeneratedName(format, format), Is.False);
		}

		/// <summary>
		/// An otherwise generated class with an abbreviation added by the user is considered
		/// user defined.
		/// </summary>
		[Test]
		public void GeneratedNameWithAbbreviation_IsUserDefined()
		{
			IPhNCFeatures natClass = AddAutoGeneratedFeatureNaturalClass("s to n",
				new FeatVals { { "vd", "+" } });
			natClass.Abbreviation.SetAnalysisDefaultWritingSystem("Vd");

			Assert.That(RuleFormulaControl.IsFeatureBasedNCUserDefined(natClass), Is.True);
		}

		/// <summary>
		/// An abbreviation of only spaces is not one the user gave the class.
		/// </summary>
		[Test]
		public void GeneratedNameWithWhitespaceAbbreviation_IsNotUserDefined()
		{
			IPhNCFeatures natClass = AddAutoGeneratedFeatureNaturalClass("s to n",
				new FeatVals { { "vd", "+" } });
			natClass.Abbreviation.SetAnalysisDefaultWritingSystem("   ");

			Assert.That(RuleFormulaControl.IsFeatureBasedNCUserDefined(natClass), Is.False);
		}

		/// <summary>
		/// An abbreviation should be recognized in any WS.
		/// </summary>
		[Test]
		public void GeneratedNameWithAbbreviationInAnotherAnalysisWs_IsUserDefined()
		{
			Cache.ServiceLocator.WritingSystemManager.GetOrSet("de",
				out CoreWritingSystemDefinition german);
			Cache.LanguageProject.AddToCurrentAnalysisWritingSystems(german);
			IPhNCFeatures natClass = AddAutoGeneratedFeatureNaturalClass("s to n",
				new FeatVals { { "vd", "+" } });
			natClass.Abbreviation.set_String(german.Handle,
				TsStringUtils.MakeString("Sth", german.Handle));

			Assert.That(RuleFormulaControl.IsFeatureBasedNCUserDefined(natClass), Is.True);
		}

		// Formats for the IsAutoGeneratedName overload tests, independent of the resources.
		private const string GeneratedFormat = "Created automatically for rule \"{0}\"";
		private const string PrefixFormat = "Shared: {0}";
		private const string GeneratedName = "Created automatically for rule \"s to n\"";
		private const string PrefixedName = "Shared: " + GeneratedName;

		// Stand-ins for a translation, in ASCII.
		private const string OtherGeneratedFormat = "Cree automatiquement pour la regle <{0}>";
		private const string OtherPrefixFormat = "Partage : {0}";

		// A plain generated name without the shared prefix should be recognized as generated.
		[TestCase(GeneratedName, true, false, GeneratedName)]

		// A generated name with the shared prefix should be recognized as generated.
		[TestCase(PrefixedName, true, true, GeneratedName)]

		// A name with extra text before or after the generated name should not be recognized as generated.
		[TestCase("Extra " + PrefixedName, false, false, null)]
		[TestCase(PrefixedName + " extra", false, false, null)]

		// A name that is not generated should not be recognized as generated.
		[TestCase("Voiced", false, false, null)]
		public void IsAutoGeneratedName_ReportsPrefixAndUnprefixedName(string ncName,
			bool expectedResult, bool expectedHasSharedPrefix, string expectedUnprefixedName)
		{
			bool result = RuleFormulaControl.IsAutoGeneratedName(ncName,
				new[] { GeneratedFormat }, new[] { PrefixFormat },
				out bool hasSharedPrefix, out string unlabelledName);

			Assert.That(result, Is.EqualTo(expectedResult));
			Assert.That(hasSharedPrefix, Is.EqualTo(expectedHasSharedPrefix));
			Assert.That(unlabelledName, Is.EqualTo(expectedUnprefixedName));
		}

		/// <summary>
		/// A prefixed name counts as auto-generated; it must also count as prefixed.
		/// </summary>
		[Test]
		public void RuleFirstFormat_WithPrefixBeforeTheName_IsRecognisedAsPrefixed()
		{
			const string format = "{0} rule: created automatically";
			string generated = string.Format(format, "s to n");

			bool result = RuleFormulaControl.IsAutoGeneratedName("Shared: " + generated,
				new[] { format }, new[] { PrefixFormat },
				out bool hasSharedPrefix, out string unlabelledName);

			Assert.That(result, Is.True);
			Assert.That(hasSharedPrefix, Is.True);
			Assert.That(unlabelledName, Is.EqualTo(generated));
		}

		/// <summary>
		/// A prefixed name counts as auto-generated for languages where the prefix comes
		/// after the name; it must also count as prefixed.
		/// </summary>
		[Test]
		public void RuleFirstFormat_WithPrefixTextAfterTheName_IsRecognisedAsPrefixed()
		{
			const string format = "{0} rule: created automatically";
			string generated = string.Format(format, "s to n");

			bool result = RuleFormulaControl.IsAutoGeneratedName(generated + " Shared:",
				new[] { format }, new[] { "{0} Shared:" },
				out bool hasSharedPrefix, out string unlabelledName);

			Assert.That(result, Is.True);
			Assert.That(hasSharedPrefix, Is.True);
			Assert.That(unlabelledName, Is.EqualTo(generated));
		}

		/// <summary>
		/// A prefix added while the prefix was untranslated is in English, around a generated
		/// name in the interface language.
		/// </summary>
		[Test]
		public void EnglishPrefixAroundOtherLanguageName_IsRecognisedAsPrefixed()
		{
			string generated = string.Format(OtherGeneratedFormat, "s to n");

			bool result = RuleFormulaControl.IsAutoGeneratedName("Shared: " + generated,
				new[] { OtherGeneratedFormat, GeneratedFormat },
				new[] { OtherPrefixFormat, PrefixFormat },
				out bool hasSharedPrefix, out string unlabelledName);

			Assert.That(result, Is.True);
			Assert.That(hasSharedPrefix, Is.True);
			Assert.That(unlabelledName, Is.EqualTo(generated));
		}

		/// <summary>
		/// A name generated while the format was untranslated, or under an English interface,
		/// is recognized after the interface language's formats.
		/// </summary>
		[TestCase(GeneratedName, false)]
		[TestCase(PrefixedName, true)]
		public void EnglishName_IsRecognisedAfterOtherLanguageFormats(string ncName,
			bool expectedHasSharedPrefix)
		{
			bool result = RuleFormulaControl.IsAutoGeneratedName(ncName,
				new[] { OtherGeneratedFormat, GeneratedFormat },
				new[] { OtherPrefixFormat, PrefixFormat },
				out bool hasSharedPrefix, out string unlabelledName);

			Assert.That(result, Is.True);
			Assert.That(hasSharedPrefix, Is.EqualTo(expectedHasSharedPrefix));
			Assert.That(unlabelledName, Is.EqualTo(GeneratedName));
		}
	}
