using SIL.FieldWorks.Filters;
using SIL.LCModel;

namespace SIL.FieldWorks.XWorks.MorphologyEditor
{
	/// ----------------------------------------------------------------------------------------
	/// <summary>
	/// This filter passes every Natural Class except for feature-based Natural Classes
	/// that were generated automatically for a rule.
	/// </summary>
	/// ----------------------------------------------------------------------------------------
	public class ExcludeAutoGeneratedNaturalClassFilter : RecordFilter
	{
		private LcmCache m_cache;

		public override void Init(LcmCache cache, System.Xml.XmlNode filterNode)
		{
			m_cache = cache;
			base.Init(cache, filterNode);
		}

		/// <summary>
		/// Allows the cache to be reset when restoring from persistence.
		/// </summary>
		public override LcmCache Cache
		{
			set
			{
				base.Cache = value;
				m_cache = value;
			}
		}

		public override bool Accept(IManyOnePathSortItem item)
		{
			// Reject the item ONLY if it is a feature-based Natural Class
			// that was generated automatically.
			var nc = item.RootObjectUsing(m_cache) as IPhNCFeatures;
			if (nc != null && !RuleFormulaControl.IsFeatureBasedNCUserDefined(nc))
				return false;
			return true;
		}

	}
}
