using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using System.Xml;
using System.Xml.Linq;
using SIL.LCModel;

namespace SIL.FieldWorks.IText
{
	/// <summary>
	/// Produces a "LaTeX Interlinear for Publication" (LT-22712) .tex document from a saved
	/// per-project template and a set of chosen texts, and produces the single resolved entry a
	/// live preview needs. This is the pipeline the (not yet built, semi-avalonia-blocked)
	/// Avalonia
	/// dialog will call -- it has no UI dependency itself.
	/// </summary>
	public static class InterlinearTemplateExporter
	{
		private const string DocumentHeader =
@"% Generated by FieldWorks' LaTeX Interlinear for Publication export.
% Everything between a \ea and its matching \z is a self-contained
% gb4e interlinear example; copy just those blocks into an existing
% paper if you don't need this file's own preamble.
% Zero-width spaces (not representable under inputenc) were removed
% during export; a '?' marks a character that was already corrupt in
% the source project's data, not something lost by this export.
\documentclass{article}
\usepackage[utf8]{inputenc}
\usepackage[T1]{fontenc}
\usepackage{gb4e}
\begin{document}
";
		private const string DocumentFooter = "\\end{document}\n";

		/// <summary>Validates the template, then exports every entry of every chosen text as a
		/// full, compilable .tex document.</summary>
		public static string Export(LcmCache cache, IReadOnlyList<IStText> texts, string templateText,
			InterlinearTemplateWritingSystemMapping wsMapping, int analysisWs)
		{
			var errors = InterlinearTemplateValidator.Validate(templateText);
			if (errors.Count > 0)
				throw new InvalidOperationException("Template is not valid: " + string.Join(" ", errors));

			var sb = new StringBuilder();
			sb.Append(DocumentHeader);
			var usedFields = ParseUsedFields(templateText);
			var lineChoices = InterlinearTemplateLineChoicesBuilder.Build(cache, usedFields, wsMapping, analysisWs);
			foreach (var text in texts)
			{
				var exported = ExportToXml(cache, text, lineChoices);
				AppendTitleComment(sb, exported);
				foreach (var entry in InterlinearTemplateEntryBuilder.BuildEntries(exported, cache, usedFields, wsMapping, analysisWs))
					sb.Append(InterlinearTemplateResolver.Resolve(templateText, entry)).Append('\n');
			}
			sb.Append(DocumentFooter);
			return sb.ToString();
		}

		/// <summary>The resolved text of just the first entry of the first text, for the live
		/// preview -- doesn't require a valid template, so an in-progress edit still
		/// previews.</summary>
		public static string PreviewFirstEntry(LcmCache cache, IStText firstText, string templateText,
			InterlinearTemplateWritingSystemMapping wsMapping, int analysisWs)
		{
			var entry = BuildEntriesForText(cache, firstText, templateText, wsMapping, analysisWs).FirstOrDefault();
			return entry == null ? string.Empty : InterlinearTemplateResolver.Resolve(templateText, entry);
		}

		private static IEnumerable<InterlinearTemplateEntry> BuildEntriesForText(LcmCache cache, IStText text,
			string templateText, InterlinearTemplateWritingSystemMapping wsMapping, int analysisWs)
		{
			var usedFields = ParseUsedFields(templateText);
			var lineChoices = InterlinearTemplateLineChoicesBuilder.Build(cache, usedFields, wsMapping, analysisWs);
			var exported = ExportToXml(cache, text, lineChoices);
			return InterlinearTemplateEntryBuilder.BuildEntries(exported, cache, usedFields, wsMapping, analysisWs);
		}

		private static HashSet<InterlinearTemplateField> ParseUsedFields(string templateText)
		{
			var used = new HashSet<InterlinearTemplateField>();
			foreach (System.Text.RegularExpressions.Match match in
				System.Text.RegularExpressions.Regex.Matches(InterlinearTemplateHelpText.RemoveHelpText(templateText), @"\{\{(\w+)\}\}"))
			{
				if (InterlinearTemplateFields.TryGetField(match.Groups[1].Value, out var field))
					used.Add(field);
			}
			return used;
		}

		private static XDocument ExportToXml(LcmCache cache, IStText text, InterlinLineChoices lineChoices)
		{
			var settings = new XmlWriterSettings { Encoding = Encoding.UTF8, Indent = false };
			using (var vc = new InterlinVc(cache))
			using (var stream = new MemoryStream())
			{
				vc.LineChoices = lineChoices;
				using (var writer = XmlWriter.Create(stream, settings))
				{
					var exporter = InterlinearExporter.Create(null, cache, writer, text, lineChoices, vc);
					exporter.WriteBeginDocument();
					exporter.ExportDisplay();
					exporter.WriteEndDocument();
					writer.Flush();
				}
				stream.Seek(0, SeekOrigin.Begin);
				return XDocument.Load(stream);
			}
		}

		private static void AppendTitleComment(StringBuilder sb, XDocument exported)
		{
			var title = exported.Descendants("interlinear-text").FirstOrDefault()
				?.Elements("item").FirstOrDefault(e => (string)e.Attribute("type") == "title")?.Value;
			if (!string.IsNullOrWhiteSpace(title))
				sb.Append("\n% ===== ").Append(InterlinearTemplateEscaping.EscapeProse(title)).Append(" =====\n");
		}
	}
}
